#!/usr/bin/env bash
# Builds the map data in site/map/ and copies the map libraries to site/vendor/.
# Run this only when the map source data or the library versions change:
#   bash scripts/build-map.sh
#
# World: Natural Earth 1:10m Admin 0 Countries, "USA point of view", v5.1.1
#   (public domain). Download it, unzip it, and pass the .shp path:
#   https://naciscdn.org/naturalearth/10m/cultural/ne_10m_admin_0_countries_usa.zip
# US states: us-atlas (US Census Bureau cartographic boundaries), from npm.
set -euo pipefail

NE_SHP="${1:?usage: bash scripts/build-map.sh path/to/ne_10m_admin_0_countries_usa.shp}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/site/map"
VENDOR="$ROOT/site/vendor"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT" "$VENDOR"

# Keep only the ISO code. ISO_A2_EH fills the codes that ISO_A2 leaves as -99
# (for example France and Norway). Dissolve by code, so each country is one
# shape: in the USA point of view, Abkhazia and South Ossetia are Georgia, and
# small territories join France and Australia.
# Simplify by distance, finer for smaller countries: the app zooms in close on
# small countries, and a percentage setting removed whole islands (Tarawa).
# With these settings every capital stays within 9 km of its country, the same
# as the full-detail data (scripts/check-data.js checks this).
npx mapshaper -i "$NE_SHP" \
  -each 'iso2 = ISO_A2_EH' \
  -filter-fields iso2 \
  -dissolve2 iso2 \
  -simplify variable interval='this.area > 1e12 ? 3000 : this.area > 1e11 ? 2000 : this.area > 1e10 ? 1000 : 400' keep-shapes \
  -rename-layers countries \
  -o "$TMP/world.json" format=topojson quantization=100000

# Wrap the JSON as a script, so that the map also works from file://.
wrap() {
  node -e '
    const [src, name, out] = process.argv.slice(1);
    const json = require("fs").readFileSync(src, "utf8").trim();
    require("fs").writeFileSync(out, `// Generated by scripts/build-map.sh. Do not edit.\nwindow.${name} = ${json};\n`);
  ' "$1" "$2" "$3"
}
wrap "$TMP/world.json" WORLD_MAP "$OUT/world.js"
wrap "$ROOT/node_modules/us-atlas/states-10m.json" US_MAP "$OUT/us-states.js"

cp "$ROOT/node_modules/d3-array/dist/d3-array.min.js" "$VENDOR/"
cp "$ROOT/node_modules/d3-geo/dist/d3-geo.min.js" "$VENDOR/"
cp "$ROOT/node_modules/topojson-client/dist/topojson-client.min.js" "$VENDOR/"

ls -l "$OUT" "$VENDOR"
